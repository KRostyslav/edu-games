/** Межі кольорового кодування завантаження вузла. */
export const LOAD_BANDS = [
  { max: 0.3, id: "idle", label: "простоює" },
  { max: 0.7, id: "ok", label: "норма" },
  { max: 0.85, id: "warn", label: "високе" },
  { max: 1, id: "hot", label: "на межі" },
  { max: Infinity, id: "over", label: "перевантажено" },
];

export function loadBand(rho, down) {
  if (down) return "down";
  return LOAD_BANDS.find((band) => rho < band.max).id;
}

