/**
 * Порядок рівнів кампанії. Живе окремо від самих рівнів, бо на нього спираються
 * і каталог компонентів (що відкривається де), і збереження, і UI — а тягнути
 * весь контент рівнів туди, де потрібен лише порядок, немає сенсу.
 *
 * Ідентифікатори стабільні: прогрес зберігається за ними, тому переставляння
 * рівнів чи вставка нового не губить зірок гравця.
 */
export const LEVEL_ORDER = [
  "l1-1",
  "l1-2",
  "l2-1",
  "l2-2",
  "l2-3",
  "l3-1",
  "l3-2",
  "l3-3",
  "l4-1",
  "l4-2",
  "l4-3",
  "l4-4",
  "l5-1",
  "l5-2",
  "l5-3",
];

/** Контекст «усе відкрито» — пісочниця й mock interview. */
export const ALL_UNLOCKED = "all";

/**
 * Чи відкрите налаштування/компонент із позначкою `unlockId` у контексті рівня.
 * Налаштування з'являються поступово: у першій главі гравець бачить лише розмір
 * сервера, а не стіну з двадцяти перемикачів, які ще нічого йому не кажуть.
 */
export function isUnlocked(unlockId, contextId) {
  if (!unlockId || contextId === ALL_UNLOCKED) return true;
  const need = LEVEL_ORDER.indexOf(unlockId);
  const have = LEVEL_ORDER.indexOf(contextId);
  return need !== -1 && have !== -1 && need <= have;
}
