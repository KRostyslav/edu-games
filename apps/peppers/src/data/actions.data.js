/**
 * Реєстр дій — головний навчальний матеріал гри.
 *
 * Кожна дія описана однаково:
 *   why    — навіщо це роблять (фізіологія рослини);
 *   timing — чому саме в цей строк;
 *   risk   — що станеться, якщо пропустити або зробити не вчасно;
 *   apply  — ефекти, і КОЖЕН із них несе власне пояснення.
 *
 * Пояснення не дублюють логіку — вони її супроводжують. Якщо змінити число
 * в `apply`, текст поруч мусить змінитися разом із ним.
 *
 * Дві осі, яких немає у виноградника:
 *   scope    — "plant" (до конкретного горщика) чи "balcony" (до середовища);
 *   species  — для яких видів дія має сенс. Обрізати на зимівлю можна обидва
 *              види, а от прокидаються вони по-різному.
 *
 * `scope` визначає, до чого дія прив'язана в інтерфейсі, а не які шляхи їй
 * дозволено чіпати: обмивання листя однієї рослини має право знизити й
 * спільний фон кліща на балконі.
 */

