/**
 * Тихих місяців у цій грі немає — і це навчальний факт.
 *
 * Виноград узимку справді можна лишити в спокої. Перець у горщику на балконі —
 * ні: він не спить повністю, його треба зрідка поливати, за ним треба стежити
 * через кліща, і саме взимку його найлегше втратити.
 */
export const QUIET_MONTHS = [];

/** Індекс місяця в сезоні: жовтень = 0, вересень = 11. */
export function seasonIndex(month) {
  return SEASON_MONTHS.indexOf(month);
}
