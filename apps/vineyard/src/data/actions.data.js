export const ACTIONS_BY_ID = Object.fromEntries(ACTIONS.map((a) => [a.id, a]));

/** Дії, доступні в конкретному місяці для конкретного регіону. */
export function actionsForMonth(month, region) {
  return ACTIONS.filter((action) => {
    if (!action.months.includes(month)) return false;
    if (action.regions && !action.regions.includes(region.id)) return false;
    return true;
  });
}
