/** Скільки годин коштує дія зараз — деякі залежать від бюджету місяця. */
export function costOf(action, state, available) {
  return action.dynamicCost ? action.dynamicCost(state, available) : action.laborCost;
}

/**
 * Дії, доступні цього місяця.
 *
 * Одноразові зникають після використання, сценарні показуються лише у своєму
 * сценарії. Усе інше лишається на екрані завжди — навіть заблоковане: список
 * доступних дій сам по собі є навчальним матеріалом, і бачити, чого ви ще не
 * можете й чому, корисніше, ніж не бачити цього зовсім.
 */
export function actionsFor(state) {
  const used = new Set(state.usedOnce ?? []);
  return ACTIONS.filter((action) => {
    if (action.once && used.has(action.id)) return false;
    if (action.scenario && action.scenario !== state.scenarioId) return false;
    return true;
  });
}
